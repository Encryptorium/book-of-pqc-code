from .rom_simulator import RandomOracle


DEFAULT_PRIME = 2027
DEFAULT_ORDER = 1013
DEFAULT_GENERATOR = 4


@dataclass
class SchnorrKeypair:
    """Schnorr witness and public key.

    ``sk`` is the witness ``x`` in ``[1, n - 1]``. ``pk`` is
    ``h = g^x mod p``. The keypair is produced by ``keygen``.
    """

    sk: int
    pk: int


@dataclass
class InteractiveTranscript:
    """Three-move interactive Schnorr transcript.

    Fields ``commitment``, ``challenge``, ``response`` correspond to
    Schnorr's ``(a, e, z)`` triple. Element ``a`` lives in F_p^*;
    ``e`` and ``z`` live in Z_n.
    """

    commitment: int
    challenge: int
    response: int


@dataclass
class FiatShamirProof:
    """Non-interactive Fiat-Shamir-compiled Schnorr proof ``(a, z)``.

    The verifier recomputes the challenge by querying the random oracle
    at the serialized transcript prefix ``pk || a``.
    """

    commitment: int
    response: int


