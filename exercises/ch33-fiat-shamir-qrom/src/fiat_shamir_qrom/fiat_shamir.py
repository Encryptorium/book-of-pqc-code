def rewind_extract(
    pk: int,
    transcript_a: InteractiveTranscript,
    transcript_b: InteractiveTranscript,
) -> int:
    """Extract the Schnorr witness from two accepting transcripts.

    Both transcripts must share the same commitment ``a`` and have
    distinct challenges ``e_a != e_b``. The witness is recovered as
    ``x = (z_a - z_b) * (e_a - e_b)^{-1} mod n``.

    This is the classical rewinding extractor. It is the step the QROM
    reduction cannot directly replicate: rewinding requires observing
    the adversary's queries at each branch, which collapses a quantum
    superposition. Measure-and-reprogram (Chapter 33 prose) is the
    replacement technique.
    """
    # EXERCISE: implement this function.
    #
    # Two accepting transcripts that share a commitment but differ in
    # challenge yield the witness: x = (z_a - z_b) * (e_a - e_b)^{-1} mod q.
