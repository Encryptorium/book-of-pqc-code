def interactive_verify(pk: int, transcript: InteractiveTranscript) -> bool:
    """Verify a three-move Schnorr transcript.

    Returns True iff ``g^z == a * h^e mod p``, with ``(a, e, z)``
    drawn from the transcript.
    """
    if pk < 1 or pk >= DEFAULT_PRIME:
        raise ValueError("pk must lie in [1, p - 1]")
    lhs = pow(DEFAULT_GENERATOR, transcript.response, DEFAULT_PRIME)
    rhs = (
        transcript.commitment
        * pow(pk, transcript.challenge, DEFAULT_PRIME)
    ) % DEFAULT_PRIME
    return lhs == rhs


def _transcript_bytes(pk: int, commitment: int) -> bytes:
    """Serialize ``(pk, commitment)`` for the Fiat-Shamir oracle query.

    Both elements live in ``[0, p - 1]`` so two-byte encoding suffices
    (``p = 2027 < 2^11``); we use four bytes per element for a clear
    delimiter.
    """
    if pk < 0 or pk >= DEFAULT_PRIME:
        raise ValueError("pk must lie in [0, p - 1]")
    if commitment < 0 or commitment >= DEFAULT_PRIME:
        raise ValueError("commitment must lie in [0, p - 1]")
    return pk.to_bytes(4, "big") + commitment.to_bytes(4, "big")


