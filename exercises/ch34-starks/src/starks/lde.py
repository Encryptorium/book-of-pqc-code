def eval_poly(coeffs: list[int], x: int, prime: int) -> int:
    """Horner-rule polynomial evaluation modulo ``prime``.

    Raises ValueError on an empty coefficient list to keep the error
    contract consistent with the rest of the package.
    """
    if not coeffs:
        raise ValueError("coefficient list must be non-empty")
    result = 0
    for c in reversed(coeffs):
        result = (result * x + c) % prime
    return result


