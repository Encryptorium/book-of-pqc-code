def lde_domain(
    size: int = LDE_SIZE,
    generator: int = LDE_GENERATOR,
    coset_shift: int = COSET_SHIFT,
    prime: int = DEFAULT_PRIME,
) -> list[int]:
    """Return an LDE domain of size ``size`` as a coset of ``<generator>``.

    The domain is ``{coset_shift * generator^i : i = 0..size-1}``. The
    generator must have order exactly ``size``. Raises ValueError on
    non-power-of-two sizes, on an invalid generator, or on a coset
    shifter that lies inside ``<generator>`` (which would make the
    coset the subgroup itself rather than a disjoint coset).
    """
    # EXERCISE: implement this function.
    #
    # Build the order-size subgroup as powers of generator exactly as
    # trace_domain does, closing order check included, then multiply every
    # element by coset_shift. The shift is what keeps the LDE domain
    # disjoint from the trace domain, so the trace-domain vanishing
    # polynomial is nonzero at every LDE point; refuse a shift that already
    # lies inside the subgroup, because the coset would then be the subgroup
    # itself. Reject a shift that is zero modulo prime and a size that is
    # not a power of two above one. Negation-closure survives the shift
    # because -1 = g_32^16 sits inside the order-32 subgroup, and
    # negation-closure is the only structure FRI folding needs from this
    # domain.
    #
    # Reference: Chapter 34, 'Eight Fibonacci steps, one non-interactive proof' and '4.2 LDE' (Block 3)
    #
    # Proved by:
    #   tests/ch34/test_lde.py
    raise NotImplementedError("exercise: lde_domain")


