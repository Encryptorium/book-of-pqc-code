"""Low-degree extension (Reed-Solomon encoding) for Chapter 34.

The trace polynomial interpolated on the trace domain is evaluated on a
larger LDE domain to produce a Reed-Solomon codeword. FRI then proves
the codeword is close to a low-degree polynomial, which is the L2
commitment to the trace polynomial under the four-layer decomposition.

The LDE domain is a coset of the order-32 subgroup of F_97^*. Choosing
a coset (rather than the subgroup itself) keeps the LDE domain disjoint
from the trace domain, which avoids zero values of the trace-domain
vanishing polynomial at LDE points. The toy uses:

- Trace domain: <64>, the order-8 subgroup (generator 64 = 28^4).
- LDE base subgroup: <28>, the order-32 subgroup.
- LDE domain: h * <28> where h = 5, the primitive root.

Because ``5`` is outside the order-32 subgroup (5 has order 96), the
coset is disjoint from the subgroup and therefore from the trace
domain. The coset is closed under negation because -1 = 28^16 is inside
the order-32 subgroup, so the coset's negation is itself.
"""

from __future__ import annotations

from .arithmetization import DEFAULT_PRIME, TRACE_DOMAIN_GENERATOR, TRACE_LENGTH


# LDE parameters over F_97.
LDE_BLOWUP = 4
LDE_SIZE = TRACE_LENGTH * LDE_BLOWUP  # 32
# 28 has order 32 in F_97* (derived from primitive root 5 via
# 5^(96/32) = 5^3 = 125 mod 97 = 28).
LDE_GENERATOR = 28
# Coset shifter. 5 is a primitive root of F_97*, so it is not in the
# order-32 subgroup generated by 28, which guarantees the coset is
# disjoint from the subgroup.
COSET_SHIFT = 5


